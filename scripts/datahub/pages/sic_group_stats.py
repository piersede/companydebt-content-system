def load() -> dict:
    ser = json.loads((DATA / "sector_series.json").read_text(encoding="utf-8"))
    meta = json.loads((DATA / "release_metadata.json").read_text(encoding="utf-8"))
    return {"ser": ser, "meta": meta}


def group_by_code(ser: dict, code: str) -> dict:
    return next(g for g in ser["groups"] if g["code"] == code)


def section_by_code(ser: dict, code: str) -> dict:
    return next(s for s in ser["sections"] if s["code"] == code)


def division_by_code(ser: dict, code: str) -> dict:
    return next(d for d in ser["divisions"] if d["code"] == code)


def trough_year(annual: list, years: list) -> int:
    vals = [v for v in annual if v is not None]
    idx = annual.index(min(vals))
    return years[idx]


def ytd_sum(monthly: list, months: list, year: int, upto_month: int) -> int:
    return sum(
        (monthly[i] or 0) for i, m in enumerate(months)
        if int(m.split("-")[0]) == year and int(m.split("-")[1]) <= upto_month
    )


def change_phrase(current: int, prior: int | None, unchanged_vs: str = "", value_vs: str = "") -> str:
    """'up slightly from 63' / 'unchanged from the previous 12 months' /
    'down from 90', generic across every sector page — never hand-authored
    per sector. unchanged_vs/value_vs let the diff==0 case read naturally
    ("unchanged from the previous 12 months") instead of repeating the same
    number twice ("unchanged from 144 for the previous 12 months")."""
    if prior is None:
        return "no comparable prior period"
    diff = current - prior
    if diff == 0:
        return f"unchanged{unchanged_vs or f' from {format_number(prior)}'}"
    pct = abs(diff) / prior * 100 if prior else None
    size = "slightly " if pct is not None and pct < 5 else ""
    word = "up" if diff > 0 else "down"
    return f"{word} {size}from {format_number(prior)}{value_vs}"


def direction_of(current: int, prior: int | None, flat_band: float = 2.0) -> str:
    """Direction of travel between two counts, with a dead band.

    A raw current-vs-prior test calls 64 against 63 a "rise". On series this
    small that is one case, and reporting it as a rise overstates what the
    data can carry. Anything inside +/-flat_band per cent reads as flat.
    """
    if not prior:
        return "flat" if current == prior else ("rising" if current > (prior or 0) else "falling")
    pct = (current - prior) / prior * 100
    if abs(pct) < flat_band:
        return "flat"
    return "rising" if pct > 0 else "falling"


def figures(cfg: dict, c: dict) -> dict:
    ser = c["ser"]
    g = group_by_code(ser, cfg["sic_code"])
    months = ser["monthly_months"]
    years = ser["annual_years"]
    li = len(years) - 1

    latest_month = months[-1]
    latest_year, latest_mo = (int(x) for x in latest_month.split("-"))
    prior_year = latest_year - 1

    ytd_current = ytd_sum(g["monthly"], months, latest_year, latest_mo)
    ytd_prior = ytd_sum(g["monthly"], months, prior_year, latest_mo)

    rolling_current = sum(v or 0 for v in g["monthly"][-12:])
    rolling_prior = sum(v or 0 for v in g["monthly"][-24:-12]) if len(g["monthly"]) >= 24 else None

    latest_val = g["monthly"][-1]
    same_month_prior_period = f"{prior_year}-{latest_mo:02d}"
    same_month_prior_val = (
        g["monthly"][months.index(same_month_prior_period)]
        if same_month_prior_period in months else None
    )
    prev_month_val = g["monthly"][-2] if len(g["monthly"]) > 1 else None
    prev_month_label = month_full(months[-2]) if len(months) > 1 else ""

    latest_annual = g["annual"][li]
    prior_annual = g["annual"][li - 1] if li > 0 else None
    peak = max(v for v in g["annual"] if v is not None)
    peak_year = years[g["annual"].index(peak)]

    # Fixed pre-pandemic reference year (2019, not sector-derived) — a
    # meaningful baseline ("the last normal year"), unlike an arbitrary
    # "since the series began" comparison.
    pre_pandemic_year = 2019
    pre_pandemic_val = g["annual"][years.index(pre_pandemic_year)] if pre_pandemic_year in years else None
    vs_pre_pandemic_pct = (
        (latest_annual - pre_pandemic_val) / pre_pandemic_val * 100
        if pre_pandemic_val else None
    )

    return {
        "group": g, "years": years, "li": li, "months": months,
        "latest_month": latest_month, "latest_year": latest_year, "latest_mo": latest_mo,
        "prior_year": prior_year,
        "ytd_current": ytd_current, "ytd_prior": ytd_prior,
        "ytd_change_phrase": change_phrase(ytd_current, ytd_prior),
        "rolling_current": rolling_current, "rolling_prior": rolling_prior,
        "rolling_change_phrase": change_phrase(
            rolling_current, rolling_prior,
            unchanged_vs=" from the previous 12 months", value_vs=" for the previous 12 months",
        ),
        "latest_val": latest_val, "prev_month_val": prev_month_val, "prev_month_label": prev_month_label,
        "same_month_prior_val": same_month_prior_val,
        "latest_annual": latest_annual, "prior_annual": prior_annual,
        "annual_change_phrase": change_phrase(latest_annual, prior_annual),
        "peak": peak, "peak_year": peak_year,
        "base_val": g["annual"][0], "base_year": years[0],
        "pre_pandemic_year": pre_pandemic_year, "pre_pandemic_val": pre_pandemic_val,
        "vs_pre_pandemic_pct": vs_pre_pandemic_pct,
    }


def sector_fact(cfg: dict, c: dict, f: dict) -> dict:
    """Data-driven comparison of the sector to its parent SIC section: entirely
    computed from sector_series.json, no per-sector authoring needed. Generic
    across every future sector page in this family. Leads with the
    year-to-date comparison (the current story); the multi-year annual band
    is kept as supporting context, not the headline claim."""
    ser = c["ser"]
    years = f["years"]
    months = f["months"]
    # The peer group used for the year-to-date share/change comparison. Defaults
    # to the broad SIC section, but a sector whose most meaningful peer is its
    # own division (e.g. temporary staffing vs employment activities, SIC 78,
    # rather than all of administrative and support services) can set
    # parent_kind="division" + parent_label. The annual trough context below
    # stays section-based regardless, since that is genuinely about the wider
    # section's cycle.
    if cfg.get("parent_kind") == "division":
        parent = division_by_code(ser, cfg["division_code"])
        parent_label = cfg["parent_label"]
    else:
        parent = section_by_code(ser, cfg["parent_section_code"])
        parent_label = cfg["parent_section_label"]
    section = section_by_code(ser, cfg["parent_section_code"])
    g = f["group"]

    parent_ytd_current = ytd_sum(parent["monthly"], months, f["latest_year"], f["latest_mo"])
    parent_ytd_prior = ytd_sum(parent["monthly"], months, f["prior_year"], f["latest_mo"])
    share_ytd_current = round(f["ytd_current"] / parent_ytd_current * 100, 1) if parent_ytd_current else None
    share_ytd_prior = round(f["ytd_prior"] / parent_ytd_prior * 100, 1) if parent_ytd_prior else None
    sector_change_pct = (f["ytd_current"] - f["ytd_prior"]) / f["ytd_prior"] * 100 if f["ytd_prior"] else None
    parent_change_pct = (parent_ytd_current - parent_ytd_prior) / parent_ytd_prior * 100 if parent_ytd_prior else None

    jan_period = f"{f['latest_year']}-01"
    jan_label = month_full(jan_period).split()[0] if jan_period in months else "January"
    latest_month_name = month_full(f["latest_month"])
    ytd_label = f"{jan_label} to {latest_month_name}"
    ytd_label_and = f"{jan_label} and {latest_month_name}"

    shares = [
        round(g["annual"][i] / parent["annual"][i] * 100, 1)
        for i in range(len(years)) if parent["annual"][i]
    ]
    share_min, share_max = min(shares), max(shares)
    band_note = (
        f"a narrow {share_min}% to {share_max}% band"
        if (share_max - share_min) < 5
        else f"a {share_min}% to {share_max}% range"
    )

    g_trough = trough_year(g["annual"], years)
    p_trough = trough_year(section["annual"], years)
    t_trough = trough_year(ser["total"]["annual"], years)
    pandemic_years = (2020, 2021)
    if g_trough in pandemic_years:
        trough_note = (
            f"Recorded insolvencies reached their series low of {format_number(g['annual'][years.index(g_trough)])} "
            f"in {g_trough}, when pandemic restrictions and government support distorted normal "
            f"insolvency patterns."
        )
    else:
        trough_note = (
            f"Recorded insolvencies reached their series low of "
            f"{format_number(g['annual'][years.index(g_trough)])} in {g_trough}."
        )
    if g_trough == p_trough != t_trough:
        if g_trough == f["base_year"]:
            # The trough is simply the first year of the series (a growing
            # sector, not a dip) — "a year after/before" would be nonsensical
            # here, since there is no earlier data point to compare against.
            trough_note += (
                f" {cfg['parent_section_label'].capitalize()} overall shows the same "
                f"pattern: {g_trough} was its lowest year too, both series having "
                f"climbed fairly steadily since the data begins."
            )
        else:
            gap = g_trough - t_trough
            plural = "s" if abs(gap) != 1 else ""
            timing = f"{gap} year{plural} after" if gap > 0 else f"{abs(gap)} year{plural} before"
            trough_note += (
                f" That was in step with {cfg['parent_section_label']} overall, which "
                f"also troughed in {g_trough}, {timing} the wider economy's {t_trough} low."
            )

    return {
        "parent_label": parent_label,
        "ytd_label": ytd_label,
        "ytd_label_and": ytd_label_and,
        "parent_ytd_current": parent_ytd_current,
        "parent_ytd_prior": parent_ytd_prior,
        "share_ytd_current": share_ytd_current,
        "share_ytd_prior": share_ytd_prior,
        "sector_change_pct": sector_change_pct,
        "parent_change_pct": parent_change_pct,
        "trough_note": trough_note,
        "band_note": band_note,
        "share_stat": (
            f"{cfg['plural'].capitalize()} accounted for {share_ytd_current}% of all "
            f"{parent_label} company insolvencies in the {ytd_label} period "
            f"({format_number(f['ytd_current'])} of {format_number(parent_ytd_current)} cases), "
            f"{'up' if share_ytd_current >= share_ytd_prior else 'down'} from "
            f"{share_ytd_prior}% over the same months of {f['prior_year']}."
        ),
        "annual_context": (
            f"Over the full {f['base_year']} to {years[f['li']]} annual series, "
            f"{cfg['eyebrow'].lower()}'s share of {cfg['parent_section_label']} insolvencies "
            f"has held to {band_note}, despite {cfg['parent_section_label']} overall "
            f"swinging much further year to year."
        ),
    }


