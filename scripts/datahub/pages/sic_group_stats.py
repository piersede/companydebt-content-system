def annual_narrative(cfg: dict, f: dict) -> str:
    """Data-driven rise/peak/recent-trend story for the annual series —
    generic across every sector, not hand-authored per page."""
    g, years, li = f["group"], f["years"], f["li"]
    peak, peak_year = f["peak"], f["peak_year"]
    base_val, base_year = f["base_val"], f["base_year"]
    latest_year, latest = years[li], f["latest_annual"]
    parts = []
    if peak_year != base_year:
        parts.append(
            f"{cfg['eyebrow']} insolvencies rose from {format_number(base_val)} in "
            f"{base_year} to a peak of {format_number(peak)} in {peak_year}."
        )
    if peak_year != latest_year and peak:
        pct = (latest - peak) / peak * 100
        word = "fallen" if pct < 0 else "risen"
        parts.append(
            f"Since then, insolvencies have {word} {abs(round(pct))}% to "
            f"{format_number(latest)} in {latest_year}."
        )
    _, pp_sentence = pre_pandemic_phrase(f)
    parts.append(pp_sentence)
    return " ".join(parts)


