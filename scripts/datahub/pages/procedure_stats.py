def assemble(slug: str, c: dict) -> str:
    cfg = PROCEDURES[slug]
    f = figures(cfg, c)
    meta = c["meta"]
    body = "\n".join([
        f"<style>{DASHBOARD_CSS}</style>",
        '<div class="cd-data-hub">',
        masthead_block(),
        hero_block(cfg, f, meta),
        srcstrip_block(),
        trend_block(cfg, c),
        context_block(cfg),
        table_block(cfg, c),
        methodology_block(include_industry_limit=False),
        source_block(cfg, meta),
        final_cta_block(),
        '</div>',
    ])
    return SENTINEL + "\n<!-- wp:html -->\n" + body + "\n<!-- /wp:html -->\n"


def main(argv: list[str]) -> int:
    targets = argv or list(PROCEDURES)
    c = load_common()
    DRAFTS.mkdir(parents=True, exist_ok=True)
    for slug in targets:
        if slug not in PROCEDURES:
            print(f"unknown slug: {slug}")
            return 2
        cfg = PROCEDURES[slug]
        out = DRAFTS / f"{cfg['wp_id']}_{slug}.html"
        out.write_text(assemble(slug, c), encoding="utf-8")
        f = figures(cfg, c)
        print(f"wrote {out.name}: latest={f['latest']} share={f['share']}% rate={f['rate']} ({f['month']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
