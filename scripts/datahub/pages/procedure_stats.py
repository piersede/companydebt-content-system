def context_block(cfg: dict) -> str:
    notes = "".join(f"<p class=\"cd-side-note__d\">{n}</p>" for n in cfg["notes"])
    if cfg.get("related"):
        notes += f"<p class=\"cd-side-note__d\">{cfg['related']}</p>"
    return dedent(f"""\
    <section class="cd-section cd-w-standard" id="about">
      <div class="cd-section-head">
        <p class="cd-eyebrow">How to read this</p>
        <h2>What the {cfg['abbr'].lower() if cfg['abbr'].isupper() else cfg['eyebrow'].lower()} figures show</h2>
      </div>
      <div class="cd-side-notes">{notes}</div>
    </section>
    """)


def table_block(cfg: dict, c: dict, n: int = 13) -> str:
    months, vals, total = c["months"], c["series"][cfg["key"]], c["series"]["total"]
    body = []
    for i in range(len(months) - n, len(months)):
        share = round(vals[i] / total[i] * 100) if total[i] else 0
        body.append(
            f"<tr><th scope=\"row\">{month_label(months[i])}</th>"
            f"<td class=\"cd-num\">{format_number(vals[i])}</td>"
            f"<td class=\"cd-num\">{format_number(total[i])}</td>"
            f"<td class=\"cd-num\">{share}%</td></tr>"
        )
    rows_html = "".join(reversed(body))
    return dedent(f"""\
    <section class="cd-section cd-w-standard" id="recent">
      <div class="cd-section-head">
        <p class="cd-eyebrow">Recent months</p>
        <h2>UK {cfg['plural']} over the last 12 months</h2>
      </div>
      <div class="cd-tablewrap">
        <table class="cd-table">
          <caption class="cd-table__caption">Monthly {cfg['plural']} in England and Wales, set against all company insolvencies and shown as a share of the total. Seasonally adjusted. Source: Insolvency Service / Companies House.</caption>
          <thead>
            <tr><th scope="col">Month</th><th scope="col" class="cd-num">{cfg['abbr']}</th><th scope="col" class="cd-num">All insolvencies</th><th scope="col" class="cd-num">Share</th></tr>
          </thead>
          <tbody>{rows_html}</tbody>
        </table>
      </div>
      <p class="cd-source-note">Seasonally adjusted, England and Wales. Source: Insolvency Service / Companies House.</p>
    </section>
    """)


