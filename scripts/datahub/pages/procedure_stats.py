def load_common() -> dict:
    monthly = json.loads((DATA / "monthly_series.json").read_text(encoding="utf-8"))
    meta = json.loads((DATA / "release_metadata.json").read_text(encoding="utf-8"))
    csv_path = sorted(glob.glob(str(DATA / "source_long_run_*.csv")))[-1]
    with open(csv_path, encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    return {"months": monthly["months"], "series": monthly["series"], "meta": meta, "rows": rows}


def last_numeric(rows: list[dict], col: str):
    for r in reversed(rows):
        try:
            return float(r.get(col, ""))
        except (TypeError, ValueError):
            continue
    return None


def pct(n: float) -> str:
    return f"{n:+.1f}%"


def figures(cfg: dict, c: dict) -> dict:
    months, series = c["months"], c["series"]
    vals = series[cfg["key"]]
    total = series["total"]
    latest = vals[-1]
    latest_total = total[-1]
    share = round(latest / latest_total * 100)
    mom = (latest - vals[-2]) / vals[-2] * 100 if vals[-2] else 0.0
    yoy = (latest - vals[-13]) / vals[-13] * 100 if len(vals) > 13 and vals[-13] else 0.0
    rate = last_numeric(c["rows"], cfg["rate_col"])
    peak = max(vals)
    peak_month = month_label(months[vals.index(peak)])
    return {
        "latest": latest,
        "latest_total": latest_total,
        "share": share,
        "mom": mom,
        "yoy": yoy,
        "rate": rate,
        "twelve": sum(vals[-12:]),
        "peak": peak,
        "peak_month": peak_month,
        "month": c["meta"]["latest_month_label"],
        "prev_month": month_label(months[-2]),
    }


